// Generates the Host protocol's TypeScript types, `src/host/protocol.ts`, from the JSON Schema a
// Rust test in `tui/crates/protocol` keeps (`tests/schema.rs`): the Host protocol's messages, the
// ACP types they carry, which method takes and gives which, and the protocol's constants.
//
//   bun scripts/protocol-types.ts           write src/host/protocol.ts
//   bun scripts/protocol-types.ts --check   fail when it is stale
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { compile, type JSONSchema } from 'json-schema-to-typescript';

const root = resolve(import.meta.dirname, '..');
export const SCHEMA = resolve(root, '../tui/crates/protocol/tests/snapshots/schema__host_protocol.snap');
export const OUTPUT = resolve(root, 'src/host/protocol.ts');

type MethodTable = {
  'x-weave-constants': Record<string, unknown>;
  'x-weave-requests': Record<string, { params: string; result: string }>;
  'x-weave-notifications': Record<string, string>;
};

/** The JSON in an insta snapshot, after its front matter. */
export function snapshotJson(text: string): unknown {
  const match = /^---\n[\s\S]*?\n---\n([\s\S]*)$/.exec(text);
  if (!match) throw new Error('The schema snapshot has no insta front matter.');
  return JSON.parse(match[1]);
}

// Annotations that may sit beside a \`$ref\` without changing what it means.
const annotations = new Set(['description', 'title', '$comment', 'default', 'examples', 'deprecated', 'readOnly', 'writeOnly']);

/**
 * In JSON Schema 2020-12 a \`$ref\` applies alongside its sibling keywords, which is how schemars
 * writes a tagged enum's variant: the shared payload by reference, with the tag beside it.
 * json-schema-to-typescript keeps only one of the two, so spell it as the \`allOf\` it means.
 */
export function splitReferences(schema: unknown): unknown {
  if (Array.isArray(schema)) return schema.map(splitReferences);
  if (typeof schema !== 'object' || schema === null) return schema;
  const entries = Object.entries(schema).map(([key, value]) => [key, splitReferences(value)] as const);
  const object = Object.fromEntries(entries) as Record<string, unknown>;
  if (typeof object.$ref !== 'string') return object;
  const siblings = Object.keys(object).filter((key) => key !== '$ref' && !annotations.has(key));
  if (siblings.length === 0) return object;
  const kept = Object.fromEntries(Object.entries(object).filter(([key]) => annotations.has(key)));
  const rest = Object.fromEntries(siblings.map((key) => [key, object[key]]));
  return { ...kept, allOf: [{ $ref: object.$ref }, rest] };
}

/**
 * An object whose properties sit beside the \`anyOf\` of what else it may hold, as schemars writes a
 * struct with a flattened enum. json-schema-to-typescript can drop the properties then, so spell
 * it as the \`allOf\` it means.
 */
export function splitAlternatives(schema: unknown): unknown {
  if (Array.isArray(schema)) return schema.map(splitAlternatives);
  if (typeof schema !== 'object' || schema === null) return schema;
  const object = Object.fromEntries(Object.entries(schema).map(([key, value]) => [key, splitAlternatives(value)])) as Record<string, unknown>;
  if (!object.properties || !object.anyOf) return object;
  const { anyOf, ...rest } = object;
  const kept = Object.fromEntries(Object.entries(rest).filter(([key]) => annotations.has(key)));
  const shape = Object.fromEntries(Object.entries(rest).filter(([key]) => !annotations.has(key)));
  return { ...kept, allOf: [shape, { anyOf }] };
}

const banner = `// Generated by \`bun scripts/protocol-types.ts\` from the Host protocol's JSON Schema
// (tui/crates/protocol/tests/snapshots/schema__host_protocol.snap). Don't edit it by hand.
`;

export async function generate(schema: JSONSchema & MethodTable): Promise<string> {
  const types = await compile(splitAlternatives(splitReferences(schema)) as JSONSchema, 'HostProtocolSchema', {
    bannerComment: banner,
    unreachableDefinitions: true,
    additionalProperties: false,
    strictIndexSignatures: false,
    format: true,
  });
  const requests = Object.entries(schema['x-weave-requests'])
    .map(([method, { params, result }]) => `  ${JSON.stringify(method)}: { params: ${params}; result: ${result} };`)
    .join('\n');
  const notifications = Object.entries(schema['x-weave-notifications'])
    .map(([method, params]) => `  ${JSON.stringify(method)}: ${params};`)
    .join('\n');
  return `${types}
/** Versions, the WebSocket's subprotocol and close codes, error codes, features and client tools. */
export const HOST_PROTOCOL = ${JSON.stringify(schema['x-weave-constants'], null, 2)} as const;

/** What each request a client sends takes, and what the Host answers. */
export interface HostRequests {
${requests}
}

/** What each notification the Host sends carries. */
export interface HostNotifications {
${notifications}
}

export type HostMethod = keyof HostRequests;
export type HostNotificationMethod = keyof HostNotifications;
`;
}

if (import.meta.main) {
  const schema = snapshotJson(await readFile(SCHEMA, 'utf8')) as JSONSchema & MethodTable;
  const generated = await generate(schema);
  if (process.argv.includes('--check')) {
    const current = await readFile(OUTPUT, 'utf8').catch(() => '');
    if (current !== generated) {
      console.error('src/host/protocol.ts is stale: run `bun scripts/protocol-types.ts`.');
      process.exit(1);
    }
  } else {
    await writeFile(OUTPUT, generated);
  }
}
