import type { TerminalBackend, TerminalBackendEvent, TerminalBackendRecord } from './terminals.ts';

type CommandResult = { code: number; stdout: string; stderr: string };
type TmuxRunner = (
  args: string[],
  options?: { cwd?: string; env?: Record<string, string> },
) => Promise<CommandResult>;

type TmuxRecord = TerminalBackendRecord & {
  paneId: string;
  windowId: string;
  cwd: string;
};

type UnsequencedTerminalBackendEvent =
  | { terminalId: string; type: 'output'; data: string }
  | { terminalId: string; type: 'title'; title: string; processName?: string }
  | { terminalId: string; type: 'exit'; exitCode?: number };

type ControlHandlers = {
  output: (paneId: string, data: string) => void;
  pause: (paneId: string) => void;
  windowClosed: (windowId: string) => void;
  boundary: () => number;
  exited: () => void;
  error: (error: Error) => void;
};

type ControlCommandResult = { stdout: string; boundary: number };
type ControlClient = {
  command(command: string): Promise<ControlCommandResult>;
  commands(commands: string[]): Promise<ControlCommandResult[]>;
  close(): void;
};
type ControlClientFactory = (input: {
  executable: string;
  args: string[];
  env: Record<string, string>;
  handlers: ControlHandlers;
}) => Promise<ControlClient>;

type TmuxTerminalBackendOptions = {
  stateDirectory: string;
  env?: Record<string, string | undefined>;
  runner?: TmuxRunner;
  controlClientFactory?: ControlClientFactory;
};

const encoder = new TextEncoder();
const decoder = new TextDecoder();
const SESSION_NAME = '_weave_product';
const CONFIG_VERSION = 'weave-product-terminal-v1';
const TMUX_REQUIRED = 'tmux is required for Weave terminals but was not found on PATH.';
const MAX_SAFE_UNIX_SOCKET_BYTES = 96;

const executableFile = (path: string) => {
  try {
    const stat = statSync(path);
    return stat.isFile() && (stat.mode === null || (stat.mode & 0o111) !== 0);
  } catch {
    return false;
  }
};

export const resolveTmuxExecutable = (
  env: Record<string, string | undefined>,
  options: {
    os?: NodeJS.Platform;
    isExecutable?: (path: string) => boolean;
  } = {},
) => {
  const configured = env.WEAVE_PORTAL_TMUX_PATH?.trim();
  if (configured) return configured;
  const isExecutable = options.isExecutable ?? executableFile;
  const pathCandidates = (env.PATH ?? '')
    .split(':')
    .filter(Boolean)
    .map((directory) => join(directory, 'tmux'));
  const platformCandidates = (options.os ?? process.platform) === 'darwin'
    ? ['/opt/homebrew/bin/tmux', '/usr/local/bin/tmux', '/usr/bin/tmux']
    : ['/usr/local/bin/tmux', '/usr/bin/tmux'];
  return [...new Set([...pathCandidates, ...platformCandidates])].find(isExecutable) ?? 'tmux';
};

const shellQuote = (value: string) => `'${value.replaceAll("'", "'\\''")}'`;

const stableSocketPath = (stateDirectory: string) => {
  const preferred = join(stateDirectory, 'terminal', 'tmux.sock');
  if (encoder.encode(preferred).byteLength <= MAX_SAFE_UNIX_SOCKET_BYTES) return preferred;
  let hash = 0xcbf29ce484222325n;
  for (const byte of encoder.encode(stateDirectory)) {
    hash ^= BigInt(byte);
    hash = BigInt.asUintN(64, hash * 0x100000001b3n);
  }
  return `/tmp/weave-product-tmux-${hash.toString(16).padStart(16, '0')}.sock`;
};
const commandEnvironment = (source: Record<string, string | undefined>) => {
  const env = Object.fromEntries(
    Object.entries(source).filter((entry): entry is [string, string] =>
      typeof entry[1] === 'string' && entry[0] !== 'NO_COLOR' && entry[0] !== 'TMUX' && entry[0] !== 'TMUX_PANE'
    ),
  );
  if (!env.LC_ALL && !env.LC_CTYPE && !env.LANG) env.LANG = 'C.UTF-8';
  return env;
};

const validTerminalName = (value: string | undefined) =>
  value && /^[A-Za-z0-9][A-Za-z0-9_.+-]*$/.test(value) ? value : undefined;

const terminalAvailable = async (name: string, env: Record<string, string>) => {
  try {
    const result = await runProcess('infocmp', {
      args: [name],
      env,
      stdout: 'ignore',
      stderr: 'ignore',
    });
    return result.success;
  } catch {
    return false;
  }
};

const resolveDefaultTerminal = async (source: Record<string, string | undefined>) => {
  const env = commandEnvironment(source);
  const override = validTerminalName(source.WEAVE_PORTAL_TMUX_TERM);
  if (override) return override;
  if (await terminalAvailable('tmux-256color', env)) return 'tmux-256color';
  return 'screen-256color';
};

